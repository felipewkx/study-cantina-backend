    private static final int INTERVALO_RELOGIO_MS = 1000;

    /**
     * Inicializa a tela principal do Sistema da Cantina.
     */
    public TelaInicial() {
        initComponents();

        // 1. Configuração dos dados iniciais e apresentação visual do texto
        Usuario visitante = new Usuario("Visitante", "", "");
        String mensagemBoasVindas = String.format(
                "<html><div style='text-align: center; line-height: 1.4; white-space: nowrap;'>"
                + "Olá, <b>%s</b>.<br>"
                + "Bem-vindo ao Sistema da Cantina!"
                + "</div></html>",
                visitante.getNome()
        );
        rotuloBemVindo.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        rotuloBemVindo.setText(mensagemBoasVindas);
        atualizarRelogio();

        // 2. Preserva as dimensões originais do conteúdo interno (600x360)
        java.awt.Container conteudoOriginal = getContentPane();
        conteudoOriginal.setPreferredSize(TAMANHO_CONTEUDO);
        conteudoOriginal.setMinimumSize(TAMANHO_CONTEUDO);
        conteudoOriginal.setMaximumSize(TAMANHO_CONTEUDO);

        // 3. Centraliza o conteúdo nos eixos X e Y via GridBagLayout
        javax.swing.JPanel painelCentralizador = new javax.swing.JPanel(new java.awt.GridBagLayout());
        painelCentralizador.setBackground(Tema.FUNDO_TELA);
        painelCentralizador.add(conteudoOriginal, new java.awt.GridBagConstraints());
        setContentPane(painelCentralizador);

        // 4. Configura a janela para operar exclusivamente em 800x600 ou Tela Cheia
        setPreferredSize(RESOLUCAO_JANELA);
        setMinimumSize(RESOLUCAO_JANELA);
        setMaximumSize(RESOLUCAO_JANELA);
        setSize(RESOLUCAO_JANELA);
        setLocationRelativeTo(null);

        addWindowStateListener(e -> {
            boolean maximizada = (e.getNewState() & java.awt.Frame.MAXIMIZED_BOTH) == java.awt.Frame.MAXIMIZED_BOTH;
            if (maximizada) {
                setMaximumSize(null);
            } else {
                setMaximumSize(RESOLUCAO_JANELA);
                setSize(RESOLUCAO_JANELA);
                setLocationRelativeTo(null);
            }
        });

        addComponentListener(new java.awt.event.ComponentAdapter() {
            @Override
            public void componentResized(java.awt.event.ComponentEvent e) {
                boolean maximizada = (getExtendedState() & java.awt.Frame.MAXIMIZED_BOTH) == java.awt.Frame.MAXIMIZED_BOTH;
                if (!maximizada && !getSize().equals(RESOLUCAO_JANELA)) {
                    setSize(RESOLUCAO_JANELA);
                }
            }
        });

        // 5. Inicia a atualização periódica do relógio
        javax.swing.Timer timer = new javax.swing.Timer(INTERVALO_RELOGIO_MS, e -> atualizarRelogio());
        timer.start();
    }

    private void atualizarRelogio() {
        java.time.format.DateTimeFormatter formato = java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy - HH:mm:ss");
        rotuloRelogio.setText(java.time.LocalDateTime.now().format(formato));
    }

    private void confirmarSaida() {
        int resposta = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente sair do sistema?",
                "Sair",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (resposta == javax.swing.JOptionPane.YES_OPTION) {
            System.exit(0);
        }
    }

