        int estadoAtual = this.getExtendedState();

        // Cria a TelaLogin e aplica o mesmo estado
        TelaLogin telaLogin = new TelaLogin();
        telaLogin.setExtendedState(estadoAtual);
        telaLogin.setVisible(true);

        // Fecha a tela atual por último
        dispose();
